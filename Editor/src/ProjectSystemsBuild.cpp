std::filesystem::path ProjectSystemsDirectory(const std::filesystem::path& projectRoot) {
    return projectRoot / kProjectSystemsDir;
}

static std::filesystem::path BuildCmakePath(const std::filesystem::path& projectRoot) {
    return projectRoot / kProjectBuildCmake;
}

static std::set<std::string> ReadExistingBuildSources(const std::filesystem::path& buildCmake) {
    std::set<std::string> sources;
    if (!std::filesystem::exists(buildCmake)) {
        return sources;
    }
    std::ifstream in(buildCmake);
    std::string line;
    while (std::getline(in, line)) {
        const std::size_t pos = line.find("${CMAKE_CURRENT_LIST_DIR}/");
        if (pos == std::string::npos) {
            continue;
        }
        const std::size_t start = pos + std::string("${CMAKE_CURRENT_LIST_DIR}/").size();
        const std::size_t end = line.find('"', start);
        if (end == std::string::npos) {
            continue;
        }
        sources.insert(line.substr(start, end - start));
    }
    return sources;
}

static bool WriteBuildCmake(const std::filesystem::path& buildCmake,
                            const std::set<std::string>& sources, std::string& error) {
    std::filesystem::create_directories(buildCmake.parent_path());
    std::ofstream out(buildCmake);
    if (!out) {
        error = "Failed to write " + buildCmake.string();
        return false;
    }
    out << "# Generated by RTypeEditor scaffold. Do not edit the source list by hand.\n";
    out << "set(RTYPE_PROJECT_SYSTEM_SOURCES\n";
    for (const std::string& source : sources) {
        out << "    \"${CMAKE_CURRENT_LIST_DIR}/" << source << "\"\n";
    }
    out << ")\n";
    if (!out) {
        error = "Failed to write " + buildCmake.string();
        return false;
    }
    return true;
}

bool AppendProjectSystemSource(const std::filesystem::path& projectRoot,
                               const std::string& cppFileName, std::string& error) {
    const std::filesystem::path buildCmake = BuildCmakePath(projectRoot);
    std::set<std::string> sources = ReadExistingBuildSources(buildCmake);
    sources.insert(cppFileName);
    return WriteBuildCmake(buildCmake, sources, error);
}

static bool EndsWith(const std::string& value, const std::string& suffix) {
    if (value.size() < suffix.size()) {
        return false;
    }
    return value.compare(value.size() - suffix.size(), suffix.size(), suffix) == 0;
}

bool RegenerateProjectRegister(const std::filesystem::path& projectRoot, std::string& error) {
    const std::filesystem::path systemsDir = ProjectSystemsDirectory(projectRoot);
    if (!std::filesystem::exists(systemsDir)) {
        return true;
    }

    std::vector<std::string> pluginHeaders;
    std::vector<std::string> systemHeaders;
    std::error_code ec;
    for (const auto& entry :
         std::filesystem::directory_iterator(systemsDir, std::filesystem::directory_options::skip_permission_denied,
                                             ec)) {
        if (ec || !entry.is_regular_file()) {
            continue;
        }
        const std::string fileName = entry.path().filename().string();
        if (!EndsWith(fileName, ".hpp")) {
            continue;
        }
        if (EndsWith(fileName, "Plugin.hpp")) {
            pluginHeaders.push_back(fileName);
        } else if (EndsWith(fileName, "System.hpp")) {
            systemHeaders.push_back(fileName);
        }
    }

    std::sort(pluginHeaders.begin(), pluginHeaders.end());
    std::sort(systemHeaders.begin(), systemHeaders.end());

    if (pluginHeaders.empty() && systemHeaders.empty()) {
        return true;
    }

    std::ostringstream body;
    body << "#ifndef RTYPE_SCAFFOLD_REGISTER_HPP_\n"
         << "#define RTYPE_SCAFFOLD_REGISTER_HPP_\n\n"
         << "#include \"ECS/Registry.hpp\"\n";

    for (const std::string& header : pluginHeaders) {
        body << "#include \"" << header << "\"\n";
    }
    for (const std::string& header : systemHeaders) {
        body << "#include \"" << header << "\"\n";
    }

    body << "\ninline void RegisterScaffoldedSystems(Engine::Registry& registry) {\n";
    for (const std::string& header : pluginHeaders) {
        const std::string pluginName = header.substr(0, header.size() - std::string(".hpp").size());
        body << "    {\n"
             << "        Engine::" << pluginName << " plugin;\n"
             << "        plugin.Init(registry);\n"
             << "    }\n";
    }
    for (const std::string& header : systemHeaders) {
        const std::string systemName = header.substr(0, header.size() - std::string(".hpp").size());
        body << "    registry.RegisterSystem<Engine::" << systemName << ">();\n";
    }
    body << "}\n\n"
         << "#endif // RTYPE_SCAFFOLD_REGISTER_HPP_\n";

    const std::filesystem::path registerPath = projectRoot / kProjectRegisterHeader;
    std::filesystem::create_directories(registerPath.parent_path());
    std::ofstream out(registerPath);
    if (!out) {
        error = "Failed to write " + registerPath.string();
        return false;
    }
    out << body.str();
    if (!out) {
        error = "Failed to write " + registerPath.string();
        return false;
    }
    return true;
}

std::string ProjectSystemsEditorBuildSnippet(const std::string& projectFolder) {
    const std::filesystem::path buildCmake = std::filesystem::path(projectFolder) / kProjectBuildCmake;
    if (!std::filesystem::exists(buildCmake)) {
        return {};
    }
    std::ostringstream snippet;
    snippet << "include(\"" << buildCmake.string() << "\")\n";
    return snippet.str();
}

std::string ProjectSystemsMainCppSnippet(const std::string& projectFolder) {
    const std::filesystem::path registerPath =
        std::filesystem::path(projectFolder) / kProjectRegisterHeader;
    if (!std::filesystem::exists(registerPath)) {
        return {};
    }
    return "#include \"rtype_scaffold_register.hpp\"\n";
}

